CREATE TABLE revinfo (
                         rev BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         revtstmp TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE holds_aud (
                           id UUID NOT NULL,
                           rev BIGINT NOT NULL,
                           revtype SMALLINT NOT NULL,

                           prison_number VARCHAR(255),
                           legacy_hold_number BIGINT,
                           sub_account_ref VARCHAR(255),
                           created_at TIMESTAMP WITH TIME ZONE,
                           created_by VARCHAR(255),
                           hold_from_date TIMESTAMP WITH TIME ZONE,
                           hold_until_date TIMESTAMP WITH TIME ZONE,
                           is_released BOOLEAN,
                           description VARCHAR(255),
                           hold_type VARCHAR(255),
                           amount BIGINT,
                           hold_location VARCHAR(255),
                           released_at TIMESTAMP WITH TIME ZONE,
                           hold_transaction_id UUID,
                           release_transaction_id UUID,

                           CONSTRAINT pk_holds_aud
                               PRIMARY KEY (id, rev),

                           CONSTRAINT fk_holds_aud_revision
                               FOREIGN KEY (rev) REFERENCES revinfo (rev)
);